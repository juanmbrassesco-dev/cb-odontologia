-- PERMITIR EL ALTA DE PROFESIONALES — etapa ⑤.6, rebanada B.
--
-- QUÉ HABILITA: que el portero pueda escribir una fila nueva en
-- `profesionales`. Hasta hoy la tabla sólo tenía `grant select`, así que un
-- alta desde el panel moría con un 42501 de Postgres: permiso denegado.
--
-- 🔴 POR QUÉ EL GRANT VA POR COLUMNAS Y NO SOBRE LA TABLA ENTERA. Un
-- `grant insert on public.profesionales` habilita TODAS las columnas, hoy y
-- las que se agreguen mañana. Nombrándolas, una columna nueva nace sin
-- permiso: el día que alguien agregue algo delicado a esta tabla, el portero
-- no va a poder escribirlo por accidente — va a tener que decidirlo.
--
-- ⚠️ `id` y `created_at` NO ESTÁN EN LA LISTA, y es a propósito: los pone la
-- base sola (`generated by default as identity` y `default now()`). Un portero
-- que pueda escribir el `id` puede pisar el de otro.
--
-- ⚠️ `activo` TAMPOCO, y es la decisión que importa de este archivo: su
-- `default` es `true`, así que un alta nace activa sin que nadie lo escriba.
-- Darle permiso de escribirlo acá sería darle al alta la capacidad de crear
-- una fila ya apagada, que no es un alta. Apagar es de la OTRA migración.
--
-- 🔑 `email_de_acceso` SÍ VA, y sin él esto no sirve para nada: es la columna
-- por la que `_shared/quien-pide.ts` busca a quien entra. Un profesional dado
-- de alta sin esa columna existe en la tabla y no puede entrar al panel.

grant insert ( nombre, apellido, email, email_de_acceso, es_admin )
  on public.profesionales
  to service_role;
